"""`tools/relock.py` re-locks a Dependabot pip PR universally, and sends nothing it should not.

Dependabot's pip updater re-resolves the locks without their headers' `--universal`, so every
pip PR it opens comes back resolved for its own runner, and
`test_a_lock_is_resolved_for_every_platform_rather_than_for_one` fails it. The script redoes the
regeneration from main's locks with each header's own command, moving only what the PR moved.

It runs on the host that holds both live tokens and can push, so most of what is pinned here is
what it refuses: a PR branch that changes anything but the three locks (whatever is on that
branch would otherwise run here, the lock tests included), a header command it does not
recognise, and a PR it was not written for. The rest is that it does what it says: the bumps it
reads, the order it regenerates in, a merge of main when the branch is behind, and a push that
is a fast-forward or nothing.

`gh` and `uv` are stand-ins on `PATH`, so nothing here reaches GitHub or an index; `git` is real,
against a bare repository in the test's own directory.
"""

from __future__ import annotations

import ast
import importlib.util
import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

import tests.test_dependency_lock as lock_tests

ROOT = Path(__file__).resolve().parents[1]
TOOL = ROOT / "tools" / "relock.py"


def _tool():
    spec = importlib.util.spec_from_file_location("relock", TOOL)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


