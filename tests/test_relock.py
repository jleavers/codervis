def test_it_regenerates_the_locks_this_repository_has_runtime_first() -> None:
    """The screenshot lock is resolved under `--constraint requirements.txt`, so the order is
    load-bearing, and a fourth lock the tool did not know of would be left as Dependabot wrote
    it."""
    order = _tool().LOCK_ORDER
    assert order[0] == "requirements.txt"
    assert set(order) == lock_tests.LOCKS
    assert len(order) == len(set(order))


@pytest.mark.parametrize("lock", sorted(lock_tests.LOCKS))
def test_it_reads_every_version_the_lock_tests_read(lock: str) -> None:
    """Two parsers of one format, kept in step: what the tool thinks a lock pins is what the
    suite that judges the lock thinks it pins."""
    text = (ROOT / lock).read_text(encoding="utf-8")
    expected = {name: pin.version for name, pin in lock_tests.locked_packages(lock).items()}
    assert _tool().parse_pins(text) == expected


def test_a_bump_is_a_version_the_branch_moved_and_nothing_else() -> None:
    before = {
        "requirements.txt": {"fastapi": "0.141.1", "uvloop": "0.22.1"},
        "requirements-dev.txt": {"fastapi": "0.141.1", "colorama": "0.4.6", "ruff": "0.16.9"},
    }
    after = {
        # A marker stripped is not a bump; nor is a package Dependabot dropped or added.
        "requirements.txt": {
            "fastapi": "0.143.3",
            "uvloop": "0.22.1",
            "opentelemetry-api": "1.45.1",
        },
        "requirements-dev.txt": {"fastapi": "0.143.3", "ruff": "0.17.1"},
    }
    assert _tool().moved_versions(before, after) == {"fastapi": "0.143.3", "ruff": "0.17.1"}


def test_one_package_moved_to_two_versions_is_refused() -> None:
    tool = _tool()
    before = {"requirements.txt": {"fastapi": "1"}, "requirements-dev.txt": {"fastapi": "1"}}
    after = {"requirements.txt": {"fastapi": "2"}, "requirements-dev.txt": {"fastapi": "3"}}
    with pytest.raises(tool.RelockError, match="fastapi"):
        tool.moved_versions(before, after)


@pytest.mark.parametrize("lock", sorted(lock_tests.LOCKS))
def test_every_header_in_this_repository_is_one_it_will_run(lock: str) -> None:
    text = (ROOT / lock).read_text(encoding="utf-8")
    argv = _tool().header_command(text, lock)
    assert argv[:3] == ["uv", "pip", "compile"]
    assert argv[-2:] == ["-o", lock]


HEADER = "# This file was autogenerated by uv via the following command:\n#    {}\nfastapi==1 \\\n"
GOOD = (
    "uv pip compile --universal --python-version 3.13 --generate-hashes --no-strip-markers"
    " requirements.in -o requirements.txt"
)


@pytest.mark.parametrize(
    "command,why",
    [
        pytest.param(GOOD.replace(" --universal", ""), "--universal", id="not-universal"),
        pytest.param(GOOD.replace(" --no-strip-markers", ""), "--no-strip-markers", id="markers"),
        pytest.param(GOOD.replace(" --generate-hashes", ""), "--generate-hashes", id="no-hashes"),
        pytest.param(
            GOOD.replace("--universal", "--universal --index-url https://example.invalid/simple"),
            "--index-url",
            id="another-index",
        ),
        pytest.param(GOOD.replace("-o requirements.txt", "-o other.txt"), "other.txt", id="output"),
        pytest.param(GOOD.replace("uv pip compile", "pip-compile"), "uv pip compile", id="tool"),
        pytest.param(GOOD + " ; true", ";", id="a-second-command"),
    ],
)
def test_a_header_it_does_not_recognise_is_refused(command: str, why: str) -> None:
    """The header is the one place the command comes from, so it is read as data and checked
    against an allow-list, never handed to a shell."""
    tool = _tool()
    with pytest.raises(tool.RelockError, match=why.replace(".", r"\.")):
        tool.header_command(HEADER.format(command), "requirements.txt")


def test_a_lock_with_no_header_is_refused() -> None:
    tool = _tool()
    with pytest.raises(tool.RelockError, match="header"):
        tool.header_command("fastapi==1 \\\n", "requirements.txt")


# ─── what it does, against a repository of its own ───────────────────────────


HASH = "--hash=sha256:" + "0" * 64
BRANCH = "dependabot/pip/fastapi-2.0"


def _lock(command: str, pins: list[str]) -> str:
    lines = ["# This file was autogenerated by uv via the following command:", f"#    {command}"]
    for pin in pins:
        lines += [f"{pin} \\", f"    {HASH}"]
    return "\n".join(lines) + "\n"


def _locks(fastapi: str, uvloop: str, *, universal: bool) -> dict[str, str]:
    """The three locks, as main has them (`universal`) or as Dependabot writes them."""
    base = "uv pip compile --universal --python-version 3.13 --generate-hashes --no-strip-markers"
    marker = " ; sys_platform != 'win32'" if universal else ""
    colorama = ["colorama==0.4.6 ; sys_platform == 'win32'"] if universal else []
    shared = [f"fastapi=={fastapi}", f"uvloop=={uvloop}{marker}"]
    return {
        "requirements.txt": _lock(f"{base} requirements.in -o requirements.txt", shared),
        "requirements-dev.txt": _lock(
            f"{base} requirements-dev.in -o requirements-dev.txt", colorama + shared
        ),
        "requirements-screenshots.txt": _lock(
            f"{base} --constraint requirements.txt requirements-screenshots.in"
            " -o requirements-screenshots.txt",
            shared + ["pillow==12.3.0"],
        ),
    }


#: `uv` as far as the tool can tell: it applies each `--upgrade-package` to the lock it is
#: pointed at, which is exactly what a resolve that keeps every other preference does here.
FAKE_UV = """\
import json, os, re, sys
args = sys.argv[1:]
with open(os.environ["FAKE_UV_LOG"], "a") as log:
    log.write(json.dumps(args) + "\\n")
out = args[args.index("-o") + 1]
text = open(out).read()
for i, arg in enumerate(args):
    if arg == "--upgrade-package" and not os.environ.get("FAKE_UV_HOLDS_BACK"):
        name, version = args[i + 1].split("==")
        text = re.sub(rf"^{re.escape(name)}==[^ \\\\]+", f"{name}=={version}", text, flags=re.M)
open(out, "w").write(text)
"""

FAKE_GH = """\
import os, sys
sys.stdout.write(open(os.environ["FAKE_GH_PR"]).read())
"""


def _git(cwd: Path, *args: str, env: dict) -> str:
    result = subprocess.run(
        ["git", *args], cwd=cwd, env=env, capture_output=True, text=True, timeout=60
    )
    assert result.returncode == 0, f"git {' '.join(args)}: {result.stderr}"
    return result.stdout.strip()


def _write(tree: Path, files: dict[str, str]) -> None:
    for name, text in files.items():
        path = tree / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


class Repo:
    """A clone with an `origin`, a main branch and a Dependabot branch, and the stand-ins."""

    def __init__(self, tmp_path: Path, *, lock_tests_pass: bool = True) -> None:
        self.tmp = tmp_path
        self.origin = tmp_path / "origin.git"
        self.clone = tmp_path / "clone"
        self.uv_log = tmp_path / "uv.log"
        self.gh_pr = tmp_path / "pr.json"
        bin_dir = tmp_path / "bin"
        bin_dir.mkdir()
        for name, source in (("uv", FAKE_UV), ("gh", FAKE_GH)):
            path = bin_dir / name
            path.write_text(f"#!{sys.executable}\n{source}", encoding="utf-8")
            path.chmod(0o755)
        self.env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
        self.env.update(
            PATH=f"{bin_dir}{os.pathsep}{os.environ['PATH']}",
            FAKE_UV_LOG=str(self.uv_log),
            FAKE_GH_PR=str(self.gh_pr),
            GIT_CONFIG_GLOBAL=os.devnull,
            GIT_CONFIG_NOSYSTEM="1",
            GIT_AUTHOR_NAME="t",
            GIT_AUTHOR_EMAIL="t@example.invalid",
            GIT_COMMITTER_NAME="t",
            GIT_COMMITTER_EMAIL="t@example.invalid",
        )
        _git(tmp_path, "init", "-q", "--bare", "-b", "main", str(self.origin), env=self.env)
        _git(tmp_path, "clone", "-q", str(self.origin), str(self.clone), env=self.env)
        body = "def test_the_locks():\n    assert {}\n".format(lock_tests_pass)
        _write(
            self.clone,
            {
                "requirements.in": "fastapi\nuvicorn\n",
                "requirements-dev.in": "-r requirements.in\npytest\n",
                "requirements-screenshots.in": "-r requirements.in\npillow\n",
                "tests/test_dependency_lock.py": body,
                **_locks("1.0", "0.1", universal=True),
            },
        )
        self.commit("main")
        _git(self.clone, "push", "-q", "origin", "main", env=self.env)

    def commit(self, message: str) -> None:
        _git(self.clone, "add", "-A", env=self.env)
        _git(self.clone, "commit", "-q", "-m", message, env=self.env)

    def open_pr(self, files: dict[str, str] | None = None, author: str = "app/dependabot") -> str:
        """Dependabot's branch: fastapi moved, and every lock resolved for one machine."""
        _git(self.clone, "checkout", "-q", "-b", BRANCH, env=self.env)
        _write(self.clone, files if files is not None else _locks("2.0", "0.1", universal=False))
        self.commit("build(deps): bump fastapi from 1.0 to 2.0")
        _git(self.clone, "push", "-q", "origin", BRANCH, env=self.env)
        self.author = author
        _git(self.clone, "checkout", "-q", "main", env=self.env)
        return self.head(BRANCH)

    def move_main(self, files: dict[str, str]) -> None:
        _write(self.clone, files)
        self.commit("main moves on")
        _git(self.clone, "push", "-q", "origin", "main", env=self.env)

    def head(self, branch: str) -> str:
        return _git(self.origin, "rev-parse", branch, env=self.env)

    def at(self, rev: str, path: str) -> str:
        return _git(self.origin, "show", f"{rev}:{path}", env=self.env) + "\n"

    def relock(
        self, *args: str, reported_head: str | None = None
    ) -> subprocess.CompletedProcess[str]:
        """Run the tool, with `gh` reporting the branch's head as it is now unless told not to."""
        pr = {
            "number": 7,
            "state": "OPEN",
            "author": {"login": self.author},
            "headRefName": BRANCH,
            "baseRefName": "main",
            "isCrossRepository": False,
            "headRefOid": reported_head or self.head(BRANCH),
        }
        self.gh_pr.write_text(json.dumps(pr), encoding="utf-8")
        return subprocess.run(
            [sys.executable, str(TOOL), "7", *args],
            cwd=self.clone,
            env=self.env,
            capture_output=True,
            text=True,
            timeout=120,
        )

    def uv_calls(self) -> list[list[str]]:
        if not self.uv_log.exists():
            return []
        return [json.loads(line) for line in self.uv_log.read_text().splitlines()]

    def worktrees(self) -> int:
        return len(_git(self.clone, "worktree", "list", env=self.env).splitlines())


def test_a_dry_run_regenerates_in_order_and_pushes_nothing(tmp_path: Path) -> None:
    repo = Repo(tmp_path)
    head = repo.open_pr()
    result = repo.relock()
    assert result.returncode == 0, result.stdout + result.stderr
    assert "fastapi 2.0" in result.stdout
    assert repo.head(BRANCH) == head, "a dry run pushed"
    calls = repo.uv_calls()
    assert [call[call.index("-o") + 1] for call in calls] == list(_tool().LOCK_ORDER)
    for call in calls:
        assert call[:4] == ["pip", "compile", "--universal", "--python-version"]
        assert call.count("--upgrade-package") == 1
        assert call[call.index("--upgrade-package") + 1] == "fastapi==2.0"
    assert repo.worktrees() == 1, "the throwaway worktree was left behind"


def test_a_push_fast_forwards_the_branch_to_main_plus_its_bumps(tmp_path: Path) -> None:
    repo = Repo(tmp_path)
    head = repo.open_pr()
    result = repo.relock("--push")
    assert result.returncode == 0, result.stdout + result.stderr
    new = repo.head(BRANCH)
    assert _git(repo.origin, "rev-parse", f"{new}^", env=repo.env) == head, "not one commit on top"
    expected = _locks("2.0", "0.1", universal=True)
    for lock, text in expected.items():
        assert repo.at(BRANCH, lock) == text, lock


def test_a_branch_behind_main_has_main_merged_in_first(tmp_path: Path) -> None:
    repo = Repo(tmp_path)
    head = repo.open_pr()
    # main moves the very lines Dependabot rewrote, which is the conflict #121 left #122 with.
    repo.move_main(_locks("1.0", "0.2", universal=True))
    result = repo.relock("--push")
    assert result.returncode == 0, result.stdout + result.stderr
    new = repo.head(BRANCH)
    parents = _git(repo.origin, "rev-list", "--parents", "-n", "1", new, env=repo.env).split()[1:]
    assert parents == [head, repo.head("main")], "not a merge of main onto the branch"
    for lock, text in _locks("2.0", "0.2", universal=True).items():
        assert repo.at(BRANCH, lock) == text, lock


def test_a_branch_that_changes_more_than_the_locks_is_refused(tmp_path: Path) -> None:
    """Whatever is on the branch runs here once it is checked out -- the lock tests included --
    so a branch carrying anything but the three locks is not one this script touches."""
    repo = Repo(tmp_path)
    files = _locks("2.0", "0.1", universal=False)
    files["tests/test_dependency_lock.py"] = "import os\n"
    head = repo.open_pr(files)
    result = repo.relock("--push")
    assert result.returncode != 0
    assert "tests/test_dependency_lock.py" in result.stdout + result.stderr
    assert repo.uv_calls() == [], "it resolved before refusing"
    assert repo.head(BRANCH) == head


def test_a_pr_dependabot_did_not_open_is_refused(tmp_path: Path) -> None:
    repo = Repo(tmp_path)
    head = repo.open_pr(author="someone")
    result = repo.relock("--push")
    assert result.returncode != 0
    assert "Dependabot" in result.stdout + result.stderr
    assert repo.uv_calls() == []
    assert repo.head(BRANCH) == head


def test_nothing_is_pushed_when_the_lock_tests_fail(tmp_path: Path) -> None:
    repo = Repo(tmp_path, lock_tests_pass=False)
    head = repo.open_pr()
    result = repo.relock("--push")
    assert result.returncode != 0
    assert "lock tests" in result.stdout + result.stderr
    assert repo.head(BRANCH) == head
    assert repo.worktrees() == 1


def test_a_bump_the_resolve_did_not_land_stops_it(tmp_path: Path) -> None:
    """A resolve that kept the old version -- a constraint the bump does not fit, say -- would
    otherwise be committed as a re-lock that moved nothing it was meant to."""
    repo = Repo(tmp_path)
    head = repo.open_pr()
    repo.env["FAKE_UV_HOLDS_BACK"] = "1"
    result = repo.relock("--push")
    assert result.returncode != 0
    assert "fastapi 1.0 after the resolve, not 2.0" in result.stderr
    assert repo.head(BRANCH) == head


def test_a_branch_that_moved_after_gh_read_it_is_refused(tmp_path: Path) -> None:
    """What was checked is what is pushed onto: a head `gh` did not report is not re-locked."""
    repo = Repo(tmp_path)
    head = repo.open_pr()
    result = repo.relock("--push", reported_head=repo.head("main"))
    assert result.returncode != 0
    assert "moved while this ran" in result.stderr
    assert repo.uv_calls() == []
    assert repo.head(BRANCH) == head


def test_a_branch_already_re_locked_is_left_alone(tmp_path: Path) -> None:
    repo = Repo(tmp_path)
    repo.open_pr()
    assert repo.relock("--push").returncode == 0
    head = repo.head(BRANCH)
    result = repo.relock("--push")
    assert result.returncode == 0, result.stdout + result.stderr
    assert "nothing to do" in result.stdout
    assert repo.head(BRANCH) == head


def test_the_tool_needs_nothing_outside_the_standard_library() -> None:
    """It is run with whichever Python the host has, which may be before any venv exists, so an
    import of anything else -- at the top or inside a function -- would fail it there."""
    tree = ast.parse(TOOL.read_text(encoding="utf-8"))
    imported = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported |= {alias.name.split(".")[0] for alias in node.names}
        elif isinstance(node, ast.ImportFrom):
            imported.add((node.module or "").split(".")[0])
    assert imported, "no imports found; is this the tool?"
    assert imported <= set(sys.stdlib_module_names), sorted(imported - set(sys.stdlib_module_names))
