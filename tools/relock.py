"""Re-lock a Dependabot pip PR universally, moving only the packages it bumps.

Usage, from a checkout of this repository::

    python tools/relock.py 124           # re-lock PR #124 in a throwaway worktree and show it
    python tools/relock.py 124 --push    # the same, then push the result to the PR's branch

Dependabot's pip updater regenerates this repository's three locks without the `--universal`
their headers ask for, so every pip PR it opens comes back resolved for its own Linux runner:
markers stripped, and packages that only another platform needs left out (#121, #122).
`tests/test_dependency_lock.py` fails such a PR, and `@dependabot recreate` only writes the same
locks again. This is the regeneration `CLAUDE.md` describes, as one command:

1. It reads the PR with `gh`, and refuses one Dependabot did not open, one from another
   repository, and one whose branch changes anything but the three locks. That branch is
   checked out and the lock tests are run from it, so nothing else on it may come along.
2. The PR's bumps are the versions its branch moved in any lock, measured from the commit it
   branched from main at, so a branch that main has since moved past is not read as a downgrade.
3. In a throwaway worktree on the branch, it merges main in if the branch is behind it, and puts
   main's three locks back. Those, and the commands in their headers, are what it starts from,
   never the branch's: a header command is checked against the one shape this script will run.
4. It runs each lock's header command, runtime lock first, with `--upgrade-package name==version`
   for every bump that lock pins, and stops if a bump did not land at its version.
5. It prints what moved against main, runs `tests/test_dependency_lock.py` in the worktree when
   this interpreter has pytest, and commits.
6. With `--push` it pushes that commit to the PR's branch as a fast-forward; without it nothing
   leaves this machine. The worktree is removed either way.

It needs `git`, `gh` and `uv` on `PATH` and nothing outside the standard library, so it runs with
whichever Python the host has. The resolve fetches package metadata from the index, as running
the header commands by hand does.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
import textwrap
from collections.abc import Mapping
from pathlib import Path

#: The locks, in the order they are regenerated. The screenshot lock is resolved under
#: `--constraint requirements.txt`, so the runtime lock has to be written first.
LOCK_ORDER = ("requirements.txt", "requirements-dev.txt", "requirements-screenshots.txt")

#: Who opens the PRs this script is for, as `gh` names the author, and where it puts them.
DEPENDABOT = "app/dependabot"
PIP_BRANCH = "dependabot/pip/"

#: The suite that judges a lock, run in the worktree before anything is committed.
LOCK_TESTS = "tests/test_dependency_lock.py"

#: The first line of a lock uv wrote; the second is the command it was written with.
HEADER = "# This file was autogenerated by uv via the following command:"

#: The one shape of header command this script runs: `uv pip compile`, these three flags, the
#: two options below with values of this shape, one input, and `-o` naming the lock itself.
#: Anything else is refused rather than passed on, `--index-url` above all.
REQUIRED_FLAGS = ("--universal", "--no-strip-markers", "--generate-hashes")
VALUE_OPTIONS = {
    "--python-version": re.compile(r"^3\.\d+$"),
    "--constraint": re.compile(r"^requirements\.txt$"),
}
INPUT = re.compile(r"^requirements(-[a-z]+)?\.in$")

#: A pin's first line: a name, optional extras, `==` and a version, then a marker or the
#: continuation onto its hashes. Hash and comment lines never start with a name.
PIN = re.compile(
    r"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)(?:\[[A-Za-z0-9,._-]+\])?==(?P<version>[^ ;\\]+)"
)


class RelockError(Exception):
    """A refusal or a failure, with the reason to show."""


def canonical(name: str) -> str:
    """PEP 503, as `tests/test_dependency_lock.py` spells a package."""
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_pins(text: str) -> dict[str, str]:
    """`{package: version}` for one lock's text."""
    pins = {}
    for line in text.splitlines():
        match = PIN.match(line)
        if match:
            pins[canonical(match.group("name"))] = match.group("version")
    return pins


def moved_versions(
    before: Mapping[str, Mapping[str, str]], after: Mapping[str, Mapping[str, str]]
) -> dict[str, str]:
    """`{package: version}` for every pin whose version moved between two sets of locks.

    A package added or dropped is not a bump, and nor is a marker: those are what a resolve
    for one machine changes, and the regeneration decides them afresh.
    """
    moved: dict[str, str] = {}
    for lock, pins in after.items():
        for name, version in pins.items():
            old = before.get(lock, {}).get(name)
            if old is None or old == version:
                continue
            if moved.setdefault(name, version) != version:
                raise RelockError(
                    f"the branch moves {name} to {moved[name]} in one lock and to {version} in "
                    "another, so there is no one version to re-lock it at"
                )
    return moved


def header_command(text: str, lock: str) -> list[str]:
    """The command in a lock's header, as an argv, once it is checked to be one to run."""
    lines = text.splitlines()
    if len(lines) < 2 or lines[0] != HEADER:
        raise RelockError(f"{lock} has no uv header to read its command from")
    try:
        argv = shlex.split(lines[1].lstrip("#").strip())
    except ValueError as exc:
        raise RelockError(f"{lock}'s header command cannot be read: {exc}") from None
    if argv[:3] != ["uv", "pip", "compile"]:
        raise RelockError(f"{lock}'s header does not run uv pip compile: {lines[1]!r}")
    flags, inputs, output = set(), [], None
    rest = argv[3:]
    index = 0
    while index < len(rest):
        token = rest[index]
        value = rest[index + 1] if index + 1 < len(rest) else None
        if token in REQUIRED_FLAGS:
            flags.add(token)
        elif token in VALUE_OPTIONS and value is not None and VALUE_OPTIONS[token].match(value):
            index += 1
        elif token == "-o" and value is not None:
            output = value
            index += 1
        elif INPUT.match(token):
            inputs.append(token)
        else:
            raise RelockError(f"{lock}'s header passes {token!r}, which this script does not run")
        index += 1
    missing = [flag for flag in REQUIRED_FLAGS if flag not in flags]
    if missing:
        raise RelockError(f"{lock}'s header does not pass {' '.join(missing)}")
    if output != lock:
        raise RelockError(f"{lock}'s header writes {output!r} rather than {lock}")
    if len(inputs) != 1:
        raise RelockError(f"{lock}'s header names {len(inputs)} inputs rather than one")
    return argv


def describe(old: Mapping[str, str], new: Mapping[str, str]) -> str:
    """What moved between two versions of one lock, for a person to read."""
    parts = []
    for name in sorted(old.keys() | new.keys()):
        was, now = old.get(name), new.get(name)
        if was == now:
            continue
        if was is None:
            parts.append(f"added {name} {now}")
        elif now is None:
            parts.append(f"removed {name} {was}")
        else:
            parts.append(f"{name} {was} -> {now}")
    return "; ".join(parts) or "unchanged"


def run(argv: list[str], cwd: Path, *, check: bool = True) -> subprocess.CompletedProcess[str]:
    result = subprocess.run(argv, cwd=cwd, capture_output=True, text=True)
    if check and result.returncode != 0:
        reason = (result.stderr or result.stdout).strip()
        raise RelockError(f"`{' '.join(argv)}` failed: {reason}")
    return result


def git(cwd: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
    return run(["git", *args], cwd, check=check)


def read_pr(number: int, repo: Path) -> dict:
    fields = "number,state,author,headRefName,baseRefName,isCrossRepository,headRefOid"
    pr = json.loads(run(["gh", "pr", "view", str(number), "--json", fields], repo).stdout)
    author = pr["author"]["login"]
    if author != DEPENDABOT:
        raise RelockError(f"#{number} was opened by {author}; this script re-locks Dependabot's")
    if not pr["headRefName"].startswith(PIP_BRANCH):
        raise RelockError(f"#{number} is not a Dependabot pip PR: {pr['headRefName']}")
    if pr["state"] != "OPEN" or pr["isCrossRepository"] or pr["baseRefName"] != "main":
        raise RelockError(f"#{number} is not an open PR into this repository's main")
    return pr


def locks_at(repo: Path, rev: str) -> dict[str, str]:
    return {lock: git(repo, "show", f"{rev}:{lock}").stdout for lock in LOCK_ORDER}


def pins_at(repo: Path, rev: str) -> dict[str, dict[str, str]]:
    return {lock: parse_pins(text) for lock, text in locks_at(repo, rev).items()}


def relock(number: int, push: bool, repo: Path) -> int:
    pr = read_pr(number, repo)
    branch = pr["headRefName"]
    main, remote = "refs/remotes/origin/main", f"refs/remotes/origin/{branch}"
    print(f"#{number}: {branch}")
    refspecs = (f"+refs/heads/main:{main}", f"+refs/heads/{branch}:{remote}")
    git(repo, "fetch", "--quiet", "origin", *refspecs)
    head = git(repo, "rev-parse", remote).stdout.strip()
    if head != pr["headRefOid"]:
        raise RelockError(f"{branch} moved while this ran; run it again")

    base = git(repo, "merge-base", main, head).stdout.strip()
    changed = git(repo, "diff", "--name-only", base, head).stdout.splitlines()
    others = sorted(set(changed) - set(LOCK_ORDER))
    if others:
        raise RelockError(
            f"{branch} changes {', '.join(others)} as well as the locks. Whatever is on the branch "
            "would run here, so this script re-locks a branch that changes the three locks and "
            "nothing else"
        )
    bumps = moved_versions(pins_at(repo, base), pins_at(repo, head))
    if not bumps:
        raise RelockError(f"{branch} moves no version in any lock")
    print("bumps: " + ", ".join(f"{name} {version}" for name, version in sorted(bumps.items())))
    main_locks = locks_at(repo, main)
    commands = {lock: header_command(main_locks[lock], lock) for lock in LOCK_ORDER}

    holder = Path(tempfile.mkdtemp(prefix="relock-"))
    tree = holder / "worktree"
    try:
        git(repo, "worktree", "add", "--quiet", "--detach", str(tree), head)
        try:
            return _relock_in(tree, branch, bumps, main_locks, commands, push)
        finally:
            git(repo, "worktree", "remove", "--force", str(tree), check=False)
    finally:
        shutil.rmtree(holder, ignore_errors=True)


def _relock_in(
    tree: Path,
    branch: str,
    bumps: Mapping[str, str],
    main_locks: Mapping[str, str],
    commands: Mapping[str, list[str]],
    push: bool,
) -> int:
    main = "refs/remotes/origin/main"
    merging = git(tree, "merge-base", "--is-ancestor", main, "HEAD", check=False).returncode != 0
    if merging:
        print("merging main in, since the branch is behind it")
        result = git(tree, "merge", "--no-commit", "--no-ff", "--quiet", main, check=False)
        conflicted = git(tree, "diff", "--name-only", "--diff-filter=U").stdout.splitlines()
        if result.returncode != 0 and not conflicted:
            raise RelockError(f"merging main failed: {(result.stderr or result.stdout).strip()}")
        others = sorted(set(conflicted) - set(LOCK_ORDER))
        if others:
            raise RelockError(f"merging main conflicts in {', '.join(others)}, which is not a lock")
    git(tree, "checkout", main, "--", *LOCK_ORDER)

    for lock in LOCK_ORDER:
        pinned = parse_pins(main_locks[lock])
        upgrades = [f"{name}=={bumps[name]}" for name in sorted(bumps) if name in pinned]
        argv = commands[lock] + ["--quiet"]
        for upgrade in upgrades:
            argv += ["--upgrade-package", upgrade]
        run(argv, tree)
        now = parse_pins((tree / lock).read_text(encoding="utf-8"))
        for name, version in sorted(bumps.items()):
            if name in pinned and now.get(name) != version:
                raise RelockError(
                    f"{lock} has {name} {now.get(name)} after the resolve, not {version}"
                )
        print(f"{lock}: {describe(pinned, now)}")

    # Against HEAD, not `status`: putting main's locks back staged them, so the index differs
    # from HEAD even when the resolve has written exactly what the branch already holds.
    unchanged = git(tree, "diff", "--quiet", "HEAD", "--", *LOCK_ORDER, check=False).returncode == 0
    if not merging and unchanged:
        print(f"nothing to do: {branch} is already re-locked")
        return 0

    if importlib.util.find_spec("pytest") is None:
        print("lock tests: not run, since this Python has no pytest; CI runs them on the push")
    else:
        result = run(
            [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", LOCK_TESTS],
            tree,
            check=False,
        )
        if result.returncode != 0:
            tail = "\n".join(result.stdout.strip().splitlines()[-15:])
            raise RelockError(
                f"the lock tests fail on the re-locked branch, so nothing was committed:\n{tail}"
            )
        print("lock tests: passed")

    summary = ", ".join(f"{name} {version}" for name, version in sorted(bumps.items()))
    title = (
        f"Merge main into {branch}, re-locking universally"
        if merging
        else f"build(deps): re-lock universally, moving only {summary}"
    )
    body = textwrap.fill(
        "Dependabot's pip updater re-resolves without the headers' `--universal`, which leaves "
        "each lock resolved for its own runner. Regenerated by tools/relock.py from main's locks "
        f"with each header's own command, runtime lock first, moving only {summary}.",
        width=72,
    )
    git(tree, "add", "--", *LOCK_ORDER)
    git(tree, "commit", "--quiet", "-m", title, "-m", body)
    commit = git(tree, "rev-parse", "--short", "HEAD").stdout.strip()
    print(f"committed {commit}: {title}")
    if not push:
        print(f"dry run: nothing pushed. Run again with --push to push it to {branch}.")
        return 0
    git(tree, "push", "--quiet", "origin", f"HEAD:refs/heads/{branch}")
    print(f"pushed {commit} to {branch}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="relock.py", description=__doc__.splitlines()[0])
    parser.add_argument("pr", type=int, help="the Dependabot pip PR's number")
    parser.add_argument(
        "--push",
        action="store_true",
        help="push the result; without it nothing leaves this machine",
    )
    args = parser.parse_args(argv)
    try:
        repo = Path(git(Path.cwd(), "rev-parse", "--show-toplevel").stdout.strip())
        return relock(args.pr, args.push, repo)
    except RelockError as exc:
        print(f"relock: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
